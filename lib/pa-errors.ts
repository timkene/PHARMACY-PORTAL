export type PaErrorCode = typeof PA_ERROR_CODES[number]
const codes = new Set<string>(PA_ERROR_CODES)
export function structuredPaError(data: unknown): { code: PaErrorCode; owningBatchId?: string | null } | undefined {
  if (!data || typeof data !== 'object') return
  const detail = (data as { detail?: unknown }).detail
  const object = detail && typeof detail === 'object' ? detail as Record<string, unknown> : undefined
  const code = typeof detail === 'string' ? detail : object?.code
  if (typeof code !== 'string' || !codes.has(code)) return
  const result: { code: PaErrorCode; owningBatchId?: string | null } = { code: code as PaErrorCode }
  if (code === 'ORDER_ALREADY_IN_ACTIVE_BATCH') {
    const id = object?.owningBatchId
    if (id === null || (typeof id === 'string' && /^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/.test(id))) result.owningBatchId = id
  }
  return result
}
